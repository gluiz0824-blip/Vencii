create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create type public.organization_role as enum (
  'owner',
  'admin',
  'approver',
  'operator',
  'viewer'
);

create type public.organization_member_status as enum (
  'invited',
  'active',
  'suspended'
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  phone text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_full_name_length check (char_length(full_name) <= 160),
  constraint profiles_phone_length check (phone is null or char_length(phone) <= 32)
);

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  legal_name text not null,
  trade_name text not null,
  cnpj text,
  timezone text not null default 'America/Sao_Paulo',
  currency text not null default 'BRL',
  owner_id uuid not null references auth.users (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint organizations_legal_name_length check (char_length(legal_name) between 2 and 180),
  constraint organizations_trade_name_length check (char_length(trade_name) between 2 and 120),
  constraint organizations_cnpj_format check (cnpj is null or cnpj ~ '^[0-9]{14}$'),
  constraint organizations_currency_format check (currency ~ '^[A-Z]{3}$')
);

create unique index organizations_cnpj_unique
  on public.organizations (cnpj)
  where cnpj is not null;
create index organizations_owner_id_idx on public.organizations (owner_id);

create table public.organization_members (
  organization_id uuid not null references public.organizations (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role public.organization_role not null,
  status public.organization_member_status not null default 'invited',
  invited_by uuid references auth.users (id) on delete set null,
  joined_at timestamptz,
  primary key (organization_id, user_id),
  constraint organization_members_active_joined_at check (status <> 'active' or joined_at is not null)
);

create unique index organization_members_one_owner
  on public.organization_members (organization_id)
  where role = 'owner';
create index organization_members_user_status_idx
  on public.organization_members (user_id, status, organization_id);

create table public.organization_invitations (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations (id) on delete cascade,
  email text not null,
  role public.organization_role not null,
  token_hash text not null unique,
  expires_at timestamptz not null,
  accepted_at timestamptz,
  invited_by uuid not null references auth.users (id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint organization_invitations_email_normalized check (email = lower(trim(email))),
  constraint organization_invitations_token_hash check (token_hash ~ '^[0-9a-f]{64}$'),
  constraint organization_invitations_owner_not_invitable check (role <> 'owner')
);

create index organization_invitations_organization_idx
  on public.organization_invitations (organization_id, accepted_at, expires_at);
create index organization_invitations_email_idx
  on public.organization_invitations (email, accepted_at);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations (id) on delete restrict,
  actor_user_id uuid references auth.users (id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  before_data jsonb,
  after_data jsonb,
  ip_hash text,
  created_at timestamptz not null default now(),
  constraint audit_logs_action_length check (char_length(action) between 3 and 120),
  constraint audit_logs_entity_type_length check (char_length(entity_type) between 1 and 80)
);

create index audit_logs_organization_created_idx
  on public.audit_logs (organization_id, created_at desc);
create index audit_logs_entity_idx
  on public.audit_logs (organization_id, entity_type, entity_id);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function private.set_updated_at();

create trigger organizations_set_updated_at
before update on public.organizations
for each row execute function private.set_updated_at();

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

alter table public.profiles enable row level security;
alter table public.organizations enable row level security;
alter table public.organization_members enable row level security;
alter table public.organization_invitations enable row level security;
alter table public.audit_logs enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, update on public.organizations to authenticated;
grant select, insert, update, delete on public.organization_members to authenticated;
grant select, insert, update, delete on public.organization_invitations to authenticated;
grant select on public.audit_logs to authenticated;

revoke all on function public.handle_new_auth_user() from public, anon, authenticated;
